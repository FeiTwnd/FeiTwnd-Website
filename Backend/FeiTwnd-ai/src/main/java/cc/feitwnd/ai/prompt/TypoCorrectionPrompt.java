package cc.feitwnd.ai.prompt;

/**
 * 文章错别字/病句纠错提示词
 *
 * 提示词按 AI 功能分文件存放（本包内一个功能一个常量类），
 * 新增功能时新增对应常量类即可，不与全局 yml 配置耦合，便于扩展。
 */
public class TypoCorrectionPrompt {

    /**
     * 纠错提示词：要求模型输出纠错后的完整 Markdown 内容。
     * 只修正错别字与病句，不改变文章结构、格式与原有表达，便于前端做逐行 diff 对比。
     */
    public static final String CORRECTION_PROMPT =
            "你是一位专业的中文编辑。请对下面的博客文章 Markdown 内容进行错别字和病句纠错。\n" +
                    "要求：\n" +
                    "1. 只修正错别字、标点误用和明显的病句，不要改变文章原有的结构、标题层级、列表、代码块、链接等 Markdown 格式。\n" +
                    "2. 不要改写或润色原文，不要增删段落，保持内容与作者原意一致。\n" +
                    "3. 未发现错误的行保持原样输出。\n" +
                    "4. 直接输出纠错后的完整 Markdown 内容，不要任何前缀、标题或解释。";
}
